/**
 * Radix menus select the item under the pointer on pointerup (press-drag-release).
 * The release of the right-click that opened the menu must never count.
 */
function ignoreSecondaryRelease(onPointerUp?: React.PointerEventHandler<HTMLDivElement>) {
  return (event: React.PointerEvent<HTMLDivElement>) => {
    onPointerUp?.(event)
    if (event.button !== 0) event.preventDefault()
  }
}

