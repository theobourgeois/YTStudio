/** The named options of a choice parameter ("Module.kParamX"), or undefined if it isn't one. */
export function choiceOptions(key: string): string[] | undefined {
  const all = CHOICES[key];
  if (!all) return undefined;
  const named = all.filter((v): v is string => v !== null);
  const fallback = DEFAULT_OPTIONS[key];
  return fallback && !named.includes(fallback) ? [fallback, ...named] : named;
}

/** What Serum shows for an option, where its parameter has a control. */
export function optionText(key: string, option: string): string | undefined {
  const shown = CHOICE_TEXT[key];
  if (!shown) return undefined;
  return shown[option] ?? (DEFAULT_OPTIONS[key] === option ? shown[""] : undefined);
}

export type ModuleType = keyof typeof MODULE_PARAMS;

export function isModuleType(name: string): name is ModuleType {
  return Object.hasOwn(MODULE_PARAMS, name);
}

/** A parameter's id in its module (what a mod slot's `destModuleParamID` says), by its name. */
export function paramId(module: ModuleType, name: string): number | undefined {
  const i = (MODULE_PARAMS[module] as readonly string[]).indexOf(name);
  return i < 0 ? undefined : i;
}

